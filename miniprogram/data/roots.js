// 取一段的释义：词首先看前缀，词尾先看后缀，中间看词根。
// 词条里写的是原文（plantar / fascia / tibialis），跟词根表不一定完全一致，
// 所以再做两步模糊：去掉常见词尾变化、按词根前缀找最长的那一段。
const ENDINGS=['s','es','ar','al','ic','ary','is','us','um','i','ae','e','y','or','er','an','ine'];
// 专名条目是按原样存的（Achilles / Chopart），用户写小写也要能查到
const CI={};for(const k in ROOTS)if(k!==k.toLowerCase())CI[k.toLowerCase()]=k;
function pick(key){
  const real=ROOTS[key]?key:CI[key];
  const r=real?ROOTS[real]:null;
  return r?{key:real,type:r.t,zh:r.zh,hint:r.hint,ex:r.ex}:null;
}
function lookup(part,index,total){
  const raw=String(part||'');
  const c=raw.toLowerCase();
  const tries=[];
  // 专名（Chopart / Lisfranc / Achilles）按原样先查一遍
  if(raw!==c)tries.push(raw,raw+'-','-'+raw);
  // 位置只是「先猜哪个」，不影响最终能不能查到：中间段也可能是后缀形态
  tries.push(c+'-','-'+c,c);
  for(const suf of ENDINGS){
    if(c.length>suf.length+2&&c.endsWith(suf))tries.push(c.slice(0,-suf.length));
  }
  for(const k of tries){const hit=pick(k);if(hit)return Object.assign({t:part},hit);}
  // 词根开头匹配：tibialis → tibi，fascia → fasc，cuneiform → cunei
  let best=null;
  for(const k in ROOTS){
    if(k.includes('-')||k.length<3)continue;
    if(c.startsWith(k)&&(!best||k.length>best.length))best=k;
    else if(c.endsWith(k)&&c.length-k.length<=2&&(!best||k.length>best.length))best=k;
  }
  if(best){const hit=pick(best);if(hit)return Object.assign({t:part},hit);}
  return {t:part,key:null,type:'',zh:'',hint:'',ex:[]};
}

// 词条写 parts:['cyber','punk']，这里换成页面直接能渲染的数组：
// 每一段带自己的释义，学习页点一下就把这段的解释弹出来。
function explainParts(parts){
  if(!Array.isArray(parts)||parts.length<2)return null;
  // 词根库查不到的那一段也不能是空白弹窗：复合词里常常是两个自由词拼的（fish·ing、cheer·ful），
  // 这种段本身就没有「词根义」，直接说明它是独立单词，比弹个空壳有用。
  return parts.map((p,i)=>{
    const hit=lookup(p,i,parts.length);
    if(hit&&hit.zh)return hit;
    return {t:p,key:null,type:'独立单词',zh:'完整的单词',
      hint:'这一段本身就是完整的英文单词，跟相邻部分拼在一起构成这个词，没有更小的词根含义。',ex:[]};
  });
}

module.exports={ROOTS,lookup,explainParts};
